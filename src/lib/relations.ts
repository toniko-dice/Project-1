/**
 * Свързаните записи, които Payload е успял да зареди.
 *
 * Връзката идва или като пълен обект, или като номер — според дълбочината
 * на заявката и според това дали Payload изобщо е намерил документа.
 * Блоковете могат да покажат само обектите; номерът не носи нито име, нито
 * снимка, нито адрес.
 *
 * **Изхвърлянето обаче не е мълчаливо.** Незаредена връзка значи, че нещо
 * е сбъркано по-нагоре — грешен `depth`, `select` без нужното поле, изтрит
 * запис или бъг в самия Payload (виж CLAUDE.md, т. 22, където точно това
 * изпразни началната страница). На екрана се вижда само липса; в дневника
 * трябва да се вижда причината.
 *
 * Едно място за правилото, а не по едно копие във всеки файл с блокове —
 * иначе предупреждението се появява на едното и липсва на другите две.
 */
export const resolvedRelations = <T,>(
  items: (number | T)[] | null | undefined,
  /** Къде се случва — влиза в предупреждението, напр. `productCarousel.products`. */
  where: string,
): T[] => {
  const list = items ?? []
  const docs = list.filter((x): x is T => typeof x !== 'number')

  if (docs.length !== list.length) {
    const номера = list.filter((x): x is number => typeof x === 'number')
    console.warn(
      `${where}: ${номера.length} от ${list.length} връзки не са заредени и не се показват (${номера.join(', ')}). ` +
        'Провери дълбочината на четенето и `defaultPopulate` на колекцията.',
    )
  }

  return docs
}
